```sql
-- E-COMMERCE SALES ANALYSIS
-- STEP 9: RFM ANALYSIS AND CUSTOMER SEGMENTATION
-- Database: ecommerce_project

USE ecommerce_project;

-- 1. Calculate Recency, Frequency and Monetary values

CREATE TEMPORARY TABLE customer_rfm AS
SELECT
    CustomerID,

    DATEDIFF(
        '2011-12-10',
        MAX(DATE(InvoiceDate))
    ) AS Recency,

    COUNT(DISTINCT InvoiceNo) AS Frequency,

    ROUND(
        SUM(Quantity * UnitPrice),
        2
    ) AS Monetary

FROM ecommerce_sales_analysis
WHERE CustomerID IS NOT NULL
GROUP BY CustomerID;


-- 2. Assign RFM scores

CREATE TEMPORARY TABLE customer_rfm_scores AS
SELECT
    CustomerID,
    Recency,
    Frequency,
    Monetary,

    NTILE(5) OVER (
        ORDER BY Recency DESC
    ) AS R_Score,

    NTILE(5) OVER (
        ORDER BY Frequency ASC
    ) AS F_Score,

    NTILE(5) OVER (
        ORDER BY Monetary ASC
    ) AS M_Score

FROM customer_rfm;


-- 3. Create customer segments

CREATE TEMPORARY TABLE customer_segments AS
SELECT
    CustomerID,
    Recency,
    Frequency,
    Monetary,
    R_Score,
    F_Score,
    M_Score,

    CASE
        WHEN R_Score >= 4 AND F_Score >= 4 AND M_Score >= 4
            THEN 'Champions'

        WHEN R_Score >= 3 AND F_Score >= 4 AND M_Score >= 3
            THEN 'Loyal Customers'

        WHEN R_Score >= 4 AND F_Score BETWEEN 2 AND 3
            THEN 'Potential Loyalists'

        WHEN R_Score = 5 AND F_Score = 1
            THEN 'Recent Customers'

        WHEN R_Score <= 2 AND F_Score >= 3
            THEN 'At Risk'

        WHEN R_Score <= 2 AND F_Score <= 2 AND M_Score <= 2
            THEN 'Hibernating'

        ELSE 'Others'
    END AS Customer_Segment

FROM customer_rfm_scores;


-- 4. Count customers in each segment

SELECT
    Customer_Segment,
    COUNT(*) AS Total_Customers
FROM customer_segments
GROUP BY Customer_Segment
ORDER BY Total_Customers DESC;


-- 5. Revenue generated by each segment

SELECT
    Customer_Segment,
    COUNT(*) AS Total_Customers,
    ROUND(SUM(Monetary), 2) AS Total_Revenue,
    ROUND(AVG(Monetary), 2) AS Average_Customer_Spending
FROM customer_segments
GROUP BY Customer_Segment
ORDER BY Total_Revenue DESC;


-- 6. View individual customer RFM details

SELECT *
FROM customer_segments
ORDER BY Monetary DESC;
